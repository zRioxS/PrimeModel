package kr.rioxs.primemodel.api.nms;

/**
 * Represents the hand used during an interaction with a model hitbox.
 *
 * @since 1.15.2
 */
public enum ModelInteractionHand {
    /**
     * The main hand (usually right).
     * @since 1.15.2
     */
    LEFT,
    /**
     * The off-hand (usually left).
     * @since 1.15.2
     */
    RIGHT
}
