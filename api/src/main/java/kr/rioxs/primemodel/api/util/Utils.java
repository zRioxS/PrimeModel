    /**
     * Lazy float provider
     */
    @ApiStatus.Internal
    public static final class LazyFloatProvider {
        private final Functions.FloatSupplier requiredTime;
        private long time = System.currentTimeMillis();
        private float storedValue;
        private boolean first = true;

        public LazyFloatProvider(long requiredTime) {
            this((float) requiredTime);
        }
        public LazyFloatProvider(float requiredTime) {
            this(() -> requiredTime);
        }
        public LazyFloatProvider(@NotNull Functions.FloatSupplier requiredTime) {
            this.requiredTime = requiredTime;
        }

        public LazyFloatProvider(float initialValue, @NotNull Functions.FloatSupplier requiredTime) {
            this(requiredTime);
            this.storedValue = initialValue;
        }

        public float updateAndGet(float updateValue) {
            var req = requiredTime.getAsFloat();
            if (req <= 0 || first) {
                first = false;
                return storedValue = updateValue;
            }
            var current = System.currentTimeMillis();
            var alpha = Math.clamp((float) (current - time) / req, 0, 1);
            time = current;
            return storedValue = InterpolationUtil.lerp(
                storedValue,
                updateValue,
                alpha
            );
        }

        public void storedValue(float storedValue) {
            this.storedValue = storedValue;
            time = System.currentTimeMillis();
        }

        public static @NotNull Supplier<Vector3f> ofVector(@NotNull Functions.FloatSupplier requiredTime, @NotNull Supplier<Vector3f> delegate) {
            Objects.requireNonNull(requiredTime);
            Objects.requireNonNull(delegate);
            var xLazy = new LazyFloatProvider(requiredTime);
            var yLazy = new LazyFloatProvider(requiredTime);
            var zLazy = new LazyFloatProvider(requiredTime);
            return () -> {
                var get = delegate.get();
                get.x = xLazy.updateAndGet(get.x);
                get.y = yLazy.updateAndGet(get.y);
                get.z = zLazy.updateAndGet(get.z);
                return get;
            };
        }
    }

    /**
     * Interpolator
     */
    @ApiStatus.Internal
    public enum VectorInterpolator {
        @SerializedName("linear")
        LINEAR {
            @NotNull
            @Override
            public Vector3f interpolate(@NotNull List<VectorPoint> points, int p2Index, float time) {
                var p1 = p2Index > 0 ? points.get(p2Index - 1) : points.getFirst();
                var p2 = points.get(p2Index);
                var t1 = p1.time();
                var t2 = p2.time();
                var a = InterpolationUtil.alpha(t1, t2, time);
                return InterpolationUtil.lerp(
                    p1.vector(InterpolationUtil.lerp(t1, t2, a)),
                    p2.vector(),
                    a
                );
            }
        },
        @SerializedName("catmullrom")
        CATMULLROM {
            private static @NotNull VectorPoint indexOf(@NotNull List<VectorPoint> list, int index, int relative) {
                var i = index + relative;
                while (i < 0) i += list.size();
                return list.get(i % list.size());
            }

            @NotNull
            @Override
            public Vector3f interpolate(@NotNull List<VectorPoint> points, int p2Index, float time) {
                var p0 = indexOf(points, p2Index, -2);
                var p1 = indexOf(points, p2Index, -1);
                var p2 = points.get(p2Index);
                var p3 = indexOf(points, p2Index, 1);
                var t1 = p1.time();
                var t2 = p2.time();
                var a = InterpolationUtil.alpha(t1, t2, time);
                return InterpolationUtil.catmull_rom(
                    p0.vector(),
                    p1.vector(InterpolationUtil.lerp(t1, t2, a)),
                    p2.vector(),
                    p3.vector(),
                    a
                );
            }
        },
        @SerializedName("bezier")
        BEZIER {
            @NotNull
            @Override
            public Vector3f interpolate(@NotNull List<VectorPoint> points, int p2Index, float time) {
                var p1 = p2Index > 0 ? points.get(p2Index - 1) : points.getFirst();
                var p2 = points.get(p2Index);
                var t1 = p1.time();
                var t2 = p2.time();
                var a = InterpolationUtil.alpha(t1, t2, time);
                return InterpolationUtil.bezier(
                    a,
                    p1.vector(InterpolationUtil.lerp(t1, t2, a)),
                    p2.vector(),
                    p1.bezier().rightTime(),
                    p1.bezier().rightValue(),
                    p2.bezier().leftTime(),
                    p2.bezier().leftValue()
                );
            }
        },
        @SerializedName("step")
        STEP {
            @NotNull
            @Override
            public Vector3f interpolate(@NotNull List<VectorPoint> points, int p2Index, float time) {
                return (p2Index > 0 ? points.get(p2Index - 1) : points.getFirst()).vector(time);
            }

            @Override
            public boolean isContinuous() {
                return false;
            }
        }
        ;

        @NotNull
        public abstract Vector3f interpolate(@NotNull List<VectorPoint> points, int p2Index, float time);

        public boolean isContinuous() {
            return true;
        }
    }

